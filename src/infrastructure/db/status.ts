import mongoose from "mongoose";

export function mongoStatus() {
  const state = mongoose.connection.readyState;

  switch (state) {
    case 0:
      return "disconnected";
    case 1:
      return "connected";
    case 2:
      return "connecting";
    case 3:
      return "disconnecting";
    default:
      return "unknown";
  }
}
